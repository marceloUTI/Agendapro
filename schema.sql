CREATE DATABASE IF NOT EXISTS agendapro CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE agendapro;
CREATE TABLE IF NOT EXISTS users (
 id INT AUTO_INCREMENT PRIMARY KEY, name VARCHAR(120) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE, password_hash VARCHAR(255) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS clients (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, name VARCHAR(120) NOT NULL,
 phone VARCHAR(30) NOT NULL DEFAULT '', email VARCHAR(190) NOT NULL DEFAULT '',
 address VARCHAR(255) NOT NULL DEFAULT '', created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS appointments (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, client_id INT NOT NULL,
 service VARCHAR(160) NOT NULL, scheduled_at DATETIME NOT NULL,
 status ENUM('Pendente','Confirmado','Concluído','Cancelado') NOT NULL DEFAULT 'Pendente',
 notes TEXT, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS estimates (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, client_id INT NOT NULL,
 service VARCHAR(160) NOT NULL, description TEXT, amount DECIMAL(12,2) NOT NULL,
 status ENUM('Pendente','Enviado','Aprovado','Recusado') NOT NULL DEFAULT 'Pendente',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
);
CREATE TABLE IF NOT EXISTS payments (
 id INT AUTO_INCREMENT PRIMARY KEY, user_id INT NOT NULL, client_id INT NOT NULL,
 description VARCHAR(160) NOT NULL, amount DECIMAL(12,2) NOT NULL,
 status ENUM('Recebido','Pendente') NOT NULL DEFAULT 'Pendente',
 paid_at DATE NOT NULL, created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
 FOREIGN KEY (client_id) REFERENCES clients(id) ON DELETE CASCADE
);
